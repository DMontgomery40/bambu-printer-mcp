#!/usr/bin/env node
// Regenerate src/safety/hidden-hms.ts from Bambu Studio's bundled English HMS
// tables. Bambu keeps some codes in a model's table but publishes no text for
// them; neither the printer screen, Bambu Studio nor Bambu Handy shows them.
// The print-safety gate treats those codes, for printers with that serial
// prefix only, as notices when they are serious or common (see validateErrors).
//
// Usage:
//   node scripts/generate-hidden-hms.mjs                     # download from the pinned commit
//   node scripts/generate-hidden-hms.mjs /path/BambuStudio   # a checkout at exactly STUDIO_TAG
//
// Raise STUDIO_TAG and STUDIO_COMMIT together, run it, and review the diff:
// added codes, codes that gained or lost their text, and the per-table SHA-256
// values are all visible there.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const STUDIO_TAG = "v02.08.02.61";
// The commit that tag points to; downloads use it so a moved tag cannot change the list.
export const STUDIO_COMMIT = "926a7192574bcb9b3a732e1ec59a46d79cb45466";
// Serial prefixes of supported models that ship a bundled table (SERIAL_MODELS
// in src/safety/printer-state.ts maps them to models).
export const PREFIXES = ["093", "094", "20P", "22E", "239", "31B"];
const OUTPUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/safety/hidden-hms.ts");

async function readTableBytes(prefix, checkout) {
  const relative = `resources/hms/hms_en_${prefix}.json`;
  // Read the committed blob, never the working tree, so local edits cannot ship as pinned data.
  if (checkout) return execFileSync("git", ["-C", checkout, "show", `${STUDIO_COMMIT}:${relative}`], { maxBuffer: 64 * 1024 * 1024 });
  const url = `https://raw.githubusercontent.com/bambulab/BambuStudio/${STUDIO_COMMIT}/${relative}`;
  const response = await fetch(url, { signal: AbortSignal.timeout(60_000) });
  if (!response.ok) throw new Error(`Download failed (${response.status}): ${url}`);
  return Buffer.from(await response.arrayBuffer());
}

/** A local checkout must contain the pinned commit at the pinned tag, or the output would mislabel its source. */
export function assertCheckoutAtTag(checkout, { run = execFileSync } = {}) {
  let described;
  try {
    described = String(run("git", ["-C", checkout, "describe", "--tags", "--exact-match", "HEAD"], { stdio: ["ignore", "pipe", "pipe"] })).trim();
  } catch (error) {
    throw new Error(`${checkout} is not a Bambu Studio checkout at a tag: ${String(error?.stderr || error?.message || error).trim()}`);
  }
  if (described !== STUDIO_TAG) throw new Error(`${checkout} is at ${described}, not the pinned ${STUDIO_TAG}.`);
  const head = String(run("git", ["-C", checkout, "rev-parse", "HEAD"], { stdio: ["ignore", "pipe", "pipe"] })).trim();
  if (head !== STUDIO_COMMIT) throw new Error(`${checkout}: tag ${STUDIO_TAG} is ${head}, not the pinned commit ${STUDIO_COMMIT}.`);
}

/**
 * Codes the table lists with empty text in every entry. A code that carries
 * text in any entry is documented and never hidden.
 */
export function hiddenCodes(table) {
  const entries = table?.data?.device_hms?.en;
  if (!Array.isArray(entries) || !entries.length) throw new Error("Table has no English device_hms entries.");
  const documented = new Set();
  const blank = new Set();
  for (const entry of entries) {
    const code = String(entry?.ecode ?? "").toUpperCase();
    if (!/^[0-9A-F]{16}$/.test(code)) throw new Error(`Malformed HMS code ${JSON.stringify(entry?.ecode)}.`);
    if (typeof entry.intro !== "string") throw new Error(`HMS ${code} has no intro field.`);
    (entry.intro.trim() ? documented : blank).add(code);
  }
  return [...blank].filter(code => !documented.has(code)).sort();
}

/** Bambu versions each model's table separately; every table must carry one. */
export function tableVersion(prefix, table) {
  const version = table?.data?.device_hms?.ver;
  if (!Number.isInteger(version) || version <= 0) throw new Error(`Table ${prefix} has no device_hms version.`);
  return version;
}

export function render({ codes, digests, versions }) {
  const body = PREFIXES.map(prefix =>
    `  "${prefix}": [\n${codes[prefix].map(code => `    "${code}",`).join("\n")}\n  ],`).join("\n");
  const sources = PREFIXES.map(prefix => `    "${prefix}": { version: ${versions[prefix]}, sha256: "${digests[prefix]}" },`).join("\n");
  return `// GENERATED by scripts/generate-hidden-hms.mjs from Bambu Studio ${STUDIO_TAG}
// (commit ${STUDIO_COMMIT}, resources/hms/hms_en_<serial prefix>.json).
// Codes Bambu lists for a serial prefix with empty text in every entry. Do not edit by hand.
export const HIDDEN_HMS_SOURCE = {
  studioTag: "${STUDIO_TAG}",
  studioCommit: "${STUDIO_COMMIT}",
  /** Per table: Bambu's device_hms version and the SHA-256 of the English file used. */
  tables: {
${sources}
  },
} as const;

export const HIDDEN_HMS: Readonly<Record<string, readonly string[]>> = {
${body}
};
`;
}

async function main() {
  const checkout = process.argv[2];
  if (checkout) assertCheckoutAtTag(checkout);
  const codes = {}, digests = {}, versions = {};
  for (const prefix of PREFIXES) {
    const bytes = await readTableBytes(prefix, checkout);
    const table = JSON.parse(bytes.toString("utf8"));
    digests[prefix] = createHash("sha256").update(bytes).digest("hex");
    versions[prefix] = tableVersion(prefix, table);
    codes[prefix] = hiddenCodes(table);
  }
  fs.writeFileSync(OUTPUT, render({ codes, digests, versions }));
  console.log(`Wrote ${OUTPUT}: ${PREFIXES.map(prefix => `${prefix}=${codes[prefix].length}`).join(", ")}`);
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
