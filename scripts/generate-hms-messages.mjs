#!/usr/bin/env node
// Regenerate src/safety/hms-messages.ts and src/printers/bambu-stages.ts from
// the same pinned Bambu Studio commit and English HMS tables that
// scripts/generate-hidden-hms.mjs reads. counterpart_print_progress uses them
// for problem messages and the words for the printer's current stage.
//
// Usage:
//   node scripts/generate-hms-messages.mjs                     # download from the pinned commit
//   node scripts/generate-hms-messages.mjs /path/BambuStudio   # a checkout at exactly STUDIO_TAG
//
// Raise the pin in scripts/generate-hidden-hms.mjs, run both generators, and
// review the diffs.
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PREFIXES, STUDIO_COMMIT, STUDIO_TAG, assertCheckoutAtTag, readStudioFile, readTableBytes, tableVersion } from "./generate-hidden-hms.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MESSAGES_OUTPUT = path.join(ROOT, "src/safety/hms-messages.ts");
const STAGES_OUTPUT = path.join(ROOT, "src/printers/bambu-stages.ts");
export const STAGE_SOURCE = "src/slic3r/GUI/DeviceManager.cpp";

/**
 * The text Bambu Studio shows for each code in one table section. Like
 * HMSQuery::_query_hms_msg, the first entry for a code wins, even when its
 * text is empty; an empty text means the table hides that code.
 */
export function sectionTexts(table, section, codePattern) {
  const entries = table?.data?.[section]?.en;
  if (!Array.isArray(entries) || !entries.length) throw new Error(`Table has no English ${section} entries.`);
  const texts = new Map();
  for (const entry of entries) {
    const code = String(entry?.ecode ?? "").toUpperCase();
    if (!codePattern.test(code)) throw new Error(`Malformed ${section} code ${JSON.stringify(entry?.ecode)}.`);
    if (typeof entry.intro !== "string") throw new Error(`${section} ${code} has no intro field.`);
    if (!texts.has(code)) texts.set(code, entry.intro.trim());
  }
  return texts;
}

/**
 * Merge per-prefix texts into one map. A code whose documented text is the
 * same everywhere maps to that string. Otherwise it maps to an object: "*" is
 * the text most tables use (ties go to the earlier prefix) and other keys are
 * the prefixes that say something different. Blank entries are left out, so
 * a printer without its own table (such as a P1S) gets the shared text.
 */
export function mergeTexts(perPrefix) {
  const codes = new Set();
  for (const texts of Object.values(perPrefix)) for (const [code, text] of texts) if (text) codes.add(code);
  const merged = {};
  for (const code of [...codes].sort()) {
    const byPrefix = PREFIXES.flatMap(prefix => {
      const text = perPrefix[prefix]?.get(code);
      return text ? [[prefix, text]] : [];
    });
    const counts = new Map();
    for (const [, text] of byPrefix) counts.set(text, (counts.get(text) ?? 0) + 1);
    const common = [...counts.entries()].sort((a, b) => b[1] - a[1])[0][0];
    const different = byPrefix.filter(([, text]) => text !== common);
    merged[code] = different.length ? { "*": common, ...Object.fromEntries(different) } : common;
  }
  return merged;
}

/** Bambu Studio's stage words, indexed by the printer's stg_cur, from get_stage_string. */
export function parseStages(source) {
  const start = source.indexOf("wxString Slic3r::get_stage_string(int stage)");
  if (start < 0) throw new Error(`${STAGE_SOURCE} has no get_stage_string.`);
  const end = source.indexOf("\n}", start);
  const body = source.slice(start, end);
  const stages = [];
  for (const match of body.matchAll(/case\s+(\d+):\s*return\s+_L\("((?:[^"\\]|\\.)*)"\);/g)) {
    const index = Number(match[1]);
    if (index !== stages.length) throw new Error(`get_stage_string skips or repeats stage ${stages.length} (found ${index}).`);
    stages.push(JSON.parse(`"${match[2]}"`));
  }
  if (stages.length < 2) throw new Error("get_stage_string has no stage strings.");
  return stages;
}

const literal = value => JSON.stringify(value);
const entry = value => typeof value === "string" ? literal(value)
  : `{ ${Object.entries(value).map(([key, text]) => `${literal(key)}: ${literal(text)}`).join(", ")} }`;

export function renderMessages({ hms, errors, sources }) {
  const tables = PREFIXES.map(prefix => {
    const source = sources[prefix];
    return `    "${prefix}": { hmsVersion: ${source.hmsVersion}, errorVersion: ${source.errorVersion}, sha256: "${source.sha256}" },`;
  }).join("\n");
  const lines = map => Object.entries(map).map(([code, value]) => `  "${code}": ${entry(value)},`).join("\n");
  return `// GENERATED by scripts/generate-hms-messages.mjs from Bambu Studio ${STUDIO_TAG}
// (commit ${STUDIO_COMMIT}, resources/hms/hms_en_<serial prefix>.json).
// English text for each documented code. A string is the text in every table
// that documents the code. An object gives "*", the text most tables use, and
// the serial prefixes whose tables say something different. Do not edit by hand.
export const HMS_MESSAGES_SOURCE = {
  studioTag: "${STUDIO_TAG}",
  studioCommit: "${STUDIO_COMMIT}",
  /** Per table: Bambu's device_hms and device_error versions, and the SHA-256 of the English file used. */
  tables: {
${tables}
  },
} as const;

export type HmsText = string | Readonly<Record<string, string>>;

/** device_hms: 16 hex digits, attr then code, as in Bambu's long error code. */
export const HMS_MESSAGES: Readonly<Record<string, HmsText>> = {
${lines(hms)}
};

/** device_error: the printer's print_error as 8 hex digits. */
export const PRINT_ERROR_MESSAGES: Readonly<Record<string, HmsText>> = {
${lines(errors)}
};
`;
}

export function renderStages({ stages, sha256 }) {
  return `// GENERATED by scripts/generate-hms-messages.mjs from Bambu Studio ${STUDIO_TAG}
// (commit ${STUDIO_COMMIT}, ${STAGE_SOURCE}, Slic3r::get_stage_string).
// The words Bambu Studio shows for the printer's current stage, indexed by stg_cur. Do not edit by hand.
export const BAMBU_STAGES_SOURCE = {
  studioTag: "${STUDIO_TAG}",
  studioCommit: "${STUDIO_COMMIT}",
  file: "${STAGE_SOURCE}",
  sha256: "${sha256}",
} as const;

export const BAMBU_STAGES: readonly string[] = [
${stages.map((text, index) => `  ${literal(text)}, // ${index}`).join("\n")}
];
`;
}

async function main() {
  const checkout = process.argv[2];
  if (checkout) assertCheckoutAtTag(checkout);
  const hmsTexts = {}, errorTexts = {}, sources = {};
  for (const prefix of PREFIXES) {
    const bytes = await readTableBytes(prefix, checkout);
    const table = JSON.parse(bytes.toString("utf8"));
    const errorVersion = table?.data?.device_error?.ver;
    if (!Number.isInteger(errorVersion) || errorVersion <= 0) throw new Error(`Table ${prefix} has no device_error version.`);
    sources[prefix] = { hmsVersion: tableVersion(prefix, table), errorVersion, sha256: createHash("sha256").update(bytes).digest("hex") };
    hmsTexts[prefix] = sectionTexts(table, "device_hms", /^[0-9A-F]{16}$/);
    errorTexts[prefix] = sectionTexts(table, "device_error", /^[0-9A-F]{8}$/);
  }
  const hms = mergeTexts(hmsTexts);
  const errors = mergeTexts(errorTexts);
  fs.writeFileSync(MESSAGES_OUTPUT, renderMessages({ hms, errors, sources }));
  const stageBytes = await readStudioFile(STAGE_SOURCE, checkout);
  const stages = parseStages(stageBytes.toString("utf8"));
  fs.writeFileSync(STAGES_OUTPUT, renderStages({ stages, sha256: createHash("sha256").update(stageBytes).digest("hex") }));
  console.log(`Wrote ${MESSAGES_OUTPUT}: ${Object.keys(hms).length} HMS and ${Object.keys(errors).length} print-error texts; ${STAGES_OUTPUT}: ${stages.length} stages`);
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
